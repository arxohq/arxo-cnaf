#!/usr/bin/env python3
"""Render README rule trees from the published APL world using law 0.2.2.

No case is evaluated. --check compares regenerated bytes without writing.
"""
import argparse
import hashlib
import json
import re
import subprocess
import textwrap
from pathlib import Path
from xml.sax.saxutils import escape

ROOT = Path(__file__).resolve().parents[1]
WORLD = ROOT / 'registry/p/fr.apl/0.1.0/world.lawir.json'
DESCRIPTOR = ROOT / 'registry/p/fr.apl/0.1.0.json'
QUERIES = [('aide_formule', 'aide-formule'), ('droit_ouvert', 'droit-ouvert')]
DEPTH = 2


def digest(data):
    return 'sha256:' + hashlib.sha256(data).hexdigest()


def run(law, args):
    return subprocess.run([law, *args], cwd=ROOT, check=True,
                          capture_output=True).stdout


def locations(anchors):
    result = []
    for anchor in anchors:
        locator = anchor.get('locator', anchor['id'].split('#')[-1])
        name = locator.removeprefix('article/')
        fragment = anchor['id'].split('#')[-1]
        if fragment.startswith('CCH_'):
            name = 'CCH ' + re.sub(r'^([LDR])(\d+)', r'\1. \2', name)
        elif fragment.startswith('ARR_'):
            name = 'Order art. ' + name
        if name not in result:
            result.append(name)
    return ' · '.join(result)


def rows(tree):
    result = []

    def visit(node, level):
        opaque = node.get('opaque')
        if opaque:
            result.append(dict(level=level, kind='test', name=opaque,
                               sources='', node=node))
            return
        kind = {'empirical': 'fact', 'institutional': 'derived',
                'judgment': 'judgment'}.get(node.get('relationKind'), 'derived')
        name = ('not ' if node.get('polarity') == 'negative' else '') + node['name']
        result.append(dict(level=level, kind=kind, name=name,
                           sources=locations(node.get('anchors', [])), node=node))
        for producer in node.get('producers', []):
            result.append(dict(level=level + 1, kind='rule', name=producer['name'],
                               sources=locations(producer.get('anchors', [])), node=producer))
            for premise in producer.get('premises', []):
                visit(premise, level + 2)

    visit(tree, 0)
    result[0]['kind'] = 'question'
    return result


def render(tree):
    width = 1040
    body = []
    y = 126
    for row in rows(tree):
        level, kind, node = row['level'], row['kind'], row['node']
        x = 28 + 22 * level
        tone = '#2454db' if kind in ('question', 'rule') else '#172b4d'
        if node.get('strength') == 'defeater':
            tone = '#895513'
        name = row['name']
        suffix = node.get('strength') if kind == 'rule' else kind
        badge = kind if kind not in ('rule', 'question') else ''
        nx = x + (len(badge) * 7.2 + 23 if badge else 0)
        notes = []
        if node.get('truncated'):
            notes.append('depth limit')
        if node.get('headPolarity') == 'negative':
            notes.append('negative head')
        if kind == 'rule':
            notes.insert(0, suffix)
        detail = ' · '.join(notes)
        lines = textwrap.wrap(name, width=max(22, (690-nx)//8),
                              break_long_words=True, break_on_hyphens=False) or ['']
        source_lines = textwrap.wrap(row['sources'], width=33) or []
        # Keep the tree compact; the unabridged native text retains all labels.
        label = node.get('label', '') if row['name'] == 'AideFormule' else ''
        line_count = max(len(lines) + bool(label), len(source_lines), 1)
        height = line_count * 20 + 8
        if kind == 'question':
            body.append(f'<rect x="16" y="{y-20}" width="1008" height="{height}" rx="9" fill="#e8efff"/>')
        elif kind == 'rule':
            body.append(f'<path d="M{x-12} {y-8} h7 m-4 -4 l-4 4 4 4" stroke="{tone}" stroke-width="1.5" fill="none"/>')
        else:
            body.append(f'<path d="M{x-12} {y-12} v12 h7" stroke="#dce4f0" stroke-width="1.2" fill="none"/>')
        if badge:
            bg = '#e8efff' if badge == 'derived' else '#f3f6fc'
            body.append(f'<rect x="{x}" y="{y-14}" width="{len(badge)*7.2+14}" height="20" rx="8" fill="{bg}"/>')
            body.append(f'<text x="{x+7}" y="{y}" class="note" fill="#5d6d86">{escape(badge)}</text>')
        for i, line in enumerate(lines):
            body.append(f'<text x="{nx}" y="{y+i*20}" class="mono" fill="{tone}" font-weight="{700 if kind in ("rule", "question") else 400}">{escape(line)}</text>')
        after = nx + len(lines[-1])*8.4 + 14
        if detail:
            body.append(f'<text x="{after}" y="{y+(len(lines)-1)*20}" class="note" fill="{tone}">{escape(detail)}</text>')
        if label:
            body.append(f'<text x="{nx}" y="{y+len(lines)*20}" class="note" fill="#5d6d86">{escape(label)}</text>')
        for i, line in enumerate(source_lines):
            body.append(f'<text x="730" y="{y+i*20}" class="source" fill="#895513">{escape(line)}</text>')
        y += height
    height = y + 100
    parts = [f'<svg xmlns="http://www.w3.org/2000/svg" width="{width}" height="{height}" viewBox="0 0 {width} {height}" role="img" aria-labelledby="title desc">',
             f'<title id="title">fr.apl@0.1.0: rules behind {escape(tree["name"])}</title>',
             '<desc id="desc">Generated from native unfold over the published APL world. All producer rules and premises returned at depth 2 are shown. Sources group repeated article locators; complete versioned anchors remain in the JSON. No case, date or reading is selected.</desc>',
             '<style>.mono{font-family:ui-monospace,monospace;font-size:14px}.note{font-family:Arial,Helvetica,sans-serif;font-size:12px}.source{font-family:ui-monospace,monospace;font-size:12px}</style>',
             f'<rect width="{width}" height="{height}" rx="14" fill="#fff"/>',
             f'<text x="20" y="32" font-family="Arial,Helvetica,sans-serif" font-size="20" font-weight="700" fill="#172b4d">Rules behind {escape(tree["name"])}</text>',
             '<text x="20" y="61" class="mono" fill="#5d6d86">fr.apl@0.1.0 · native unfold · depth 2</text>',
             '<text x="20" y="87" class="note" fill="#5d6d86">No case · all declared producers · no date or reading selected</text>',
             '<text x="730" y="87" class="note" fill="#895513">Source anchors</text>',
             *body,
             f'<path d="M20 {y+12} H1020" stroke="#dce4f0"/>',
             f'<text x="20" y="{y+39}" class="note" fill="#5d6d86">fact: supplied input · derived: model relation · judgment: human finding · test: comparison · defeater: exception</text>',
             f'<text x="20" y="{y+63}" class="note" fill="#5d6d86">Depth-limit markers preserve the native response. Full dated source anchors: companion JSON.</text>',
             '</svg>']
    return ('\n'.join(parts)+'\n').encode()


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--law', default='law')
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    desc = json.loads(DESCRIPTOR.read_bytes())
    if digest(WORLD.read_bytes()) != desc['worldHash']:
        raise SystemExit('Published world bytes do not match the descriptor')
    version = run(args.law, ['--version']).decode().strip()
    if version.splitlines()[0] != 'law 0.2.2':
        raise SystemExit('Use the released law 0.2.2 CLI for these retained trees')
    outputs = {}
    manifest = {'format': 'arxo.readme-unfold/0.1', 'package': 'fr.apl@0.1.0',
                'world': str(WORLD.relative_to(ROOT)), 'worldHash': desc['worldHash'],
                'producer': version.splitlines(), 'depth': DEPTH,
                'caseSelected': False, 'readingSelected': False, 'trees': []}
    for predicate, slug in QUERIES:
        cli = ['engine', 'unfold', str(WORLD.relative_to(ROOT)), predicate,
               '--depth', str(DEPTH), '--lang', 'en', '--quote', '0']
        raw = run(args.law, [*cli, '--json'])
        tree = json.loads(raw)
        outputs[f'docs/unfold/{slug}.json'] = raw
        outputs[f'docs/unfold/{slug}.txt'] = run(args.law, [*cli, '--fold'])
        outputs[f'docs/images/unfold-{slug}.svg'] = render(tree)
        manifest['trees'].append({'predicate': predicate, 'command': ['law', *cli, '--json'],
                                  'json': f'docs/unfold/{slug}.json', 'jsonHash': digest(raw),
                                  'visibleRows': len(rows(tree))})
    outputs['docs/unfold/manifest.json'] = (json.dumps(manifest, indent=2)+'\n').encode()
    for relative, data in outputs.items():
        path = ROOT / relative
        if args.check:
            if not path.exists() or path.read_bytes() != data:
                raise SystemExit(f'Generated file differs: {relative}')
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(data)
    print(f'{"Checked" if args.check else "Generated"} two native unfold trees and their SVGs')


if __name__ == '__main__':
    main()
